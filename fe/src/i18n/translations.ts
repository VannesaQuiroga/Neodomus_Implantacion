export function construirT(idioma: string): TFunc {
  return (clave, vars) => {
    const tabla = TRADUCCIONES[clave];
    const texto = tabla ? (tabla[idioma] ?? tabla.es ?? clave) : clave;
    if (!vars) return texto;
    return Object.entries(vars).reduce(
      (acc, [k, v]) => acc.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v)),
      texto,
    );
  };
}